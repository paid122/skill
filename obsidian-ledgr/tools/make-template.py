"""Generates src/cc/template.ts from spec/command-center.body.html (the prototype's markup).
Every change from the prototype is listed here, so the template stays reviewable against the spec."""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
s = (root / "spec/command-center.body.html").read_text()
s = s.replace("<body>", "", 1).strip()

def rep(a, b, count=1):
    global s
    if a not in s: sys.exit(f"not found: {a[:70]}")
    s = s.replace(a, b, count)

# 1. The API key lives in the plugin's settings (Obsidian secret storage), not in an in-page box.
s = re.sub(r'<div id="keyBox">.*?</div></div></div>\n', "", s, count=1, flags=re.S)
if 'id="keyBox"' in s: sys.exit("keyBox not removed")
# 2. Statue video: set at runtime from the plugin folder (no base64 in main.js).
rep('src="DATAURI"', "")
# 3. Bottom bar: no UNIVERSE; DASHBOARD and VAULT point at things that exist for every user.
rep('    <a class="ic" href="Universe%20View.html"><b>✺</b>UNIVERSE</a>\n', "")
rep('<a class="ic" href="Trading%20Dashboard.html">', '<a class="ic" href="https://www.ledgrjournal.app/dashboard" target="_blank" rel="noopener">')
rep('<a class="ic" href="obsidian://open?vault=claude&amp;file=00%20Home">', '<a class="ic" href="#" data-action="vault">')
# 4. Calendar comes from LEDGR, not Forex Factory (their data isn't licensed for this).
rep('<a id="ffLogo" href="https://www.forexfactory.com/calendar" target="_blank" rel="noopener">FF</a>', '<a id="ffLogo" href="#">CAL</a>')
rep('FOREX FACTORY · LOADING…', 'ECONOMIC CALENDAR · LOADING…')
rep('FOREX FACTORY · THIS WEEK', 'ECONOMIC CALENDAR · THIS WEEK')
rep('\n  <a class="chip" href="https://www.forexfactory.com/calendar" target="_blank" rel="noopener" style="margin-left:auto">OPEN FOREXFACTORY.COM ↗</a>', '<a class="chip" id="calSrc" target="_blank" rel="noopener" style="margin-left:auto;display:none"></a>')
rep('HIGH-IMPACT AHEAD <span>FOREX FACTORY</span>', 'HIGH-IMPACT AHEAD <span>ECONOMIC CALENDAR</span>')
# 5. TradingView attribution: the TRADINGVIEW labels link to tradingview.com (looks the same; color inherits).
s = s.replace('<span>5M · TRADINGVIEW</span>', '<span>5M · <a class="tvattr" href="https://www.tradingview.com/" target="_blank" rel="noopener">TRADINGVIEW</a></span>')
s = s.replace('<span>TRADINGVIEW · LIVE</span>', '<span><a class="tvattr" href="https://www.tradingview.com/" target="_blank" rel="noopener">TRADINGVIEW</a> · LIVE</span>')
s = s.replace('CHART <span>TRADINGVIEW</span>', 'CHART <span><a class="tvattr" href="https://www.tradingview.com/" target="_blank" rel="noopener">TRADINGVIEW</a></span>')

out = ("/**\n * The command center's markup: spec/command-center.body.html with the changes listed in tools/make-template.py.\n"
       " * Generated by tools/make-template.py. Static markup only; journal data is always inserted as text or escaped.\n */\n"
       f"export const TEMPLATE = {json.dumps(s, ensure_ascii=False)};\n")
(root / "src/cc/template.ts").write_text(out)
print("template.ts", len(s))
