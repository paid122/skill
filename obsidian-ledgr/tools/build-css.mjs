/**
 * Builds styles.css:
 *   1. the bundled fonts (Share Tech Mono, Rajdhani; SIL OFL 1.1) as base64 @font-face, so nothing loads from a CDN
 *   2. the plugin's own styles (src/plugin.css: settings, locked screens)
 *   3. the prototype's stylesheet (spec/command-center.css) scoped under .ledgr-cc:
 *      - :root / html / body become the .ledgr-cc root; every other selector is prefixed with it
 *      - every selector also gets a doubled root class, so Obsidian's own input/select/button styles don't leak in
 *      - @keyframes are renamed (lcc-*) so they can't clash with Obsidian's or other plugins'
 *      - viewport units become container units and @media becomes @container, because the
 *        command center lives in an Obsidian pane, not a browser window
 */
import fs from "node:fs";
import path from "node:path";
import postcss from "postcss";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const R = ".ledgr-cc.ledgr-cc"; // doubled for specificity (see above)

// ------------------------------------------------------------------ fonts
const font = (family, weight, file, range) => {
  const data = fs.readFileSync(path.join(root, "node_modules", file)).toString("base64");
  return `@font-face{font-family:'${family}';font-style:normal;font-display:block;font-weight:${weight};src:url(data:font/woff2;base64,${data}) format('woff2');unicode-range:${range}}`;
};
const LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";
const LATIN_EXT = "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF";
const fonts = [
  font("Share Tech Mono", 400, "@fontsource/share-tech-mono/files/share-tech-mono-latin-400-normal.woff2", LATIN),
  ...[500, 600, 700].flatMap((w) => [
    font("Rajdhani", w, `@fontsource/rajdhani/files/rajdhani-latin-${w}-normal.woff2`, LATIN),
    font("Rajdhani", w, `@fontsource/rajdhani/files/rajdhani-latin-ext-${w}-normal.woff2`, LATIN_EXT),
  ]),
].join("\n");

// ------------------------------------------------------------------ scope the prototype's CSS
const css = fs.readFileSync(path.join(root, "spec/command-center.css"), "utf8");
const ast = postcss.parse(css);
const renamed = new Map();

ast.walkAtRules("keyframes", (at) => { renamed.set(at.params, `lcc-${at.params}`); at.params = `lcc-${at.params}`; });
ast.walkAtRules("media", (at) => { at.name = "container"; at.params = `ledgr-cc ${at.params.replace(/^\s*/, "")}`; });

const scopeOne = (sel) => {
  const s = sel.trim();
  if (s === ":root" || s === "html" || s === "body") return R;
  if (s === "*") return `${R},${R} *`;
  const m = s.match(/^(?:html|body)(::?[\w-]+)$/); // body::after → the root's own ::after
  if (m) return `${R}${m[1]}`;
  if (/^(html|body)\b/.test(s)) throw new Error(`Unhandled root selector: ${s}`);
  return `${R} ${s}`;
};

ast.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.flatMap((s) => scopeOne(s).split(","));
});

ast.walkDecls((d) => {
  if (/^animation(-name)?$/.test(d.prop)) for (const [from, to] of renamed) d.value = d.value.replace(new RegExp(`(^|[\\s,])${from}(?=$|[\\s,])`, "g"), `$1${to}`);
  d.value = d.value.replace(/(\d*\.?\d+)vh\b/g, "$1cqh").replace(/(\d*\.?\d+)vw\b/g, "$1cqw");
});

// The root: fills the pane, is the containing block for the prototype's position:fixed overlays, and a size container.
const rootCss = `
/* ---- LEDGR Command Center (scoped port of command-center.html) ---- */
.workspace-leaf-content[data-type="ledgr-command-center"] .view-content{padding:0;overflow:hidden}
${R}{position:relative;width:100%;height:100%;overflow:hidden;contain:strict;isolation:isolate}
/* The stage holds the command center; it's the size container (so 100vh → 100cqh means "the stage") and the
   containing block for the prototype's position:fixed overlays. app.ts sizes and scales it to fit the pane. */
${R} .ledgr-cc-stage{position:absolute;left:0;top:0;width:100%;height:100%;transform-origin:0 0;container:ledgr-cc/size;contain:layout paint}
/* Obsidian styles inputs, selects and buttons globally: put them back to the browser's own look first,
   so only the prototype's rules apply (they come after and are more specific). */
${R} :is(input,select,button,textarea,a){all:revert;box-sizing:border-box}
`;

const plugin = fs.readFileSync(path.join(root, "src/plugin.css"), "utf8");
// Deliberate changes from the prototype, after its rules so they win.
const overrides = `
/* ---- changes from the prototype ---- */
/* The statue fills the OPERATOR frame top to bottom (the prototype letterboxed it). */
${R} .figwrap video{object-fit:cover;object-position:50% 100%}
`;
const out = [`/* LEDGR for Obsidian. Generated by tools/build-css.mjs: edit src/plugin.css or spec/command-center.css, not this file. */`, "/* Fonts: Share Tech Mono and Rajdhani, SIL Open Font License 1.1 (see fonts/). */", fonts, plugin, rootCss, ast.toString(), overrides].join("\n");
fs.writeFileSync(path.join(root, "styles.css"), out);
console.log(`styles.css: ${(out.length / 1024).toFixed(0)} KB`);
